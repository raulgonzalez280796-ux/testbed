"""Turn SDK exceptions into ProviderError (Anthropic and OpenAI SDKs share error classes)."""

from __future__ import annotations

from types import ModuleType

from .base import ProviderError, jsonable


def kind_for_status(status: int | None) -> str:
    if status == 429:
        return "rate_limit"
    if status in (401, 403):
        return "auth"
    if status == 404:
        return "not_found"
    if status is not None and status >= 500:
        return "server"
    if status is not None and status >= 400:
        return "bad_request"
    return "other"


def retry_after_seconds(response) -> float | None:
    if response is None:
        return None
    try:
        return float(response.headers.get("retry-after"))
    except (TypeError, ValueError, AttributeError):
        return None


def classify_stainless(error: Exception, sdk: ModuleType, request: dict) -> ProviderError:
    """For SDKs generated by Stainless: anthropic, openai."""
    status = getattr(error, "status_code", None)
    if isinstance(error, sdk.APITimeoutError):
        kind = "timeout"
    elif isinstance(error, sdk.APIConnectionError):
        kind = "connection"
    else:
        kind = kind_for_status(status)
    return ProviderError(
        kind, str(getattr(error, "message", None) or error), status_code=status,
        retry_after=retry_after_seconds(getattr(error, "response", None)),
        raw_request=jsonable(request) if request else None,
        error_type=type(error).__name__,
    )
